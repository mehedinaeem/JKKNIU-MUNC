import { test, expect } from '@playwright/test';

test('real Django session, creation, field validation, publication, closing and duplication', async ({ page }, testInfo) => {
    await page.goto('/admin/forms');
    await expect(page).toHaveURL(/\/admin\/login$/);
    await page.getByLabel('Username').fill(process.env.MUNC_E2E_USERNAME);
    await page.getByLabel('Password').fill(process.env.MUNC_E2E_PASSWORD);
    await page.getByRole('button', { name: /Sign in to your workspace/ }).click();
    await expect(page.getByRole('heading', { name: 'Registration forms', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '＋ Create form' }).click();
    const create = page.getByRole('dialog');
    await create.getByRole('combobox', { name: 'Event', exact: true }).selectOption({ label: 'Isolated test conference' });
    await create.getByLabel('Form title').fill('Conference delegate application');
    await create.getByRole('button', { name: 'Create form', exact: true }).click();
    await expect(page).toHaveURL(/\/admin\/forms\/\d+$/);
    await page.getByRole('button', { name: /Add your first question/ }).click();
    await page.getByRole('dialog').getByRole('button', { name: /Short text/ }).click();
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    await expect(page.getByLabel('Question label')).toHaveAttribute('aria-invalid', 'true');
    await page.getByLabel('Question label').fill('Full name');
    await page.getByLabel('Required question').check();
    await page.getByRole('button', { name: '＋ Add question', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: /Dropdown/ }).click();
    await page.getByLabel('Question label').fill('Preferred committee');
    await page.getByLabel('Option 1', { exact: true }).fill('General Assembly');
    await page.getByLabel('Option 2', { exact: true }).fill('Security Council');
    const day = offset => new Date(Date.now() + offset * 86400000).toISOString().slice(0, 10);
    const opens = `${day(2)}T09:00`, closes = `${day(7)}T18:00`;
    await page.getByLabel('Description', { exact: true }).fill('Welcome to the delegate application.');
    await page.getByLabel('Opens (Asia/Dhaka)').fill(opens);
    await page.getByLabel('Closes (Asia/Dhaka)').fill(closes);
    await page.getByLabel('Capacity', { exact: true }).fill('150');
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    await expect(page.getByText('Draft saved.', { exact: true })).toBeVisible();
    await page.reload();
    await expect(page.getByLabel('Form title')).toHaveValue('Conference delegate application');
    await expect(page.getByLabel('Opens (Asia/Dhaka)')).toHaveValue(opens);
    await expect(page.getByLabel('Closes (Asia/Dhaka)')).toHaveValue(closes);
    await expect(page.getByLabel('Capacity', { exact: true })).toHaveValue('150');
    await expect(page.getByLabel('Description', { exact: true })).toHaveValue('Welcome to the delegate application.');
    await page.getByRole('button', { name: 'Preview', exact: true }).click();
    await expect(page.getByRole('dialog').getByRole('option', { name: 'General Assembly' })).toBeAttached();
    await page.getByRole('button', { name: 'Back to builder' }).click();
    await page.getByRole('button', { name: 'Publish form', exact: false }).click();
    await page.getByRole('button', { name: 'Save and publish' }).click();
    await expect(page.getByText('Version 1 published. Existing responses are preserved.')).toBeVisible();
    const published = await page.request.get(`${process.env.MUNC_E2E_REAL_API}/forms/conference-delegate-application/`);
    expect(published.ok()).toBe(true);
    expect((await published.json()).schema.fields).toHaveLength(2);
    for (const width of [1440, 375]) {
        await page.setViewportSize({ width, height: 1000 });
        expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1);
        await page.screenshot({ path: testInfo.outputPath(`live-builder-${width}.png`), fullPage: true });
    }
    await page.getByRole('button', { name: 'Close form', exact: true }).click();
    await page.getByRole('button', { name: 'Save and close' }).click();
    await expect(page.getByText('Form closed. New responses are no longer accepted.')).toBeVisible();
    await page.getByRole('button', { name: 'Duplicate', exact: true }).click();
    await page.getByRole('button', { name: 'Create duplicate' }).click();
    await expect(page.getByRole('dialog', { name: 'Duplicate form' })).not.toBeVisible();
    await expect(page.getByRole('textbox', { name: 'Form title', exact: true })).toHaveValue('Conference delegate application (copy)');
    await page.getByRole('button', { name: 'Archive form', exact: true }).click();
    await page.getByRole('button', { name: 'Save and archive', exact: true }).click();
    await expect(page.getByText('Form archived. Existing responses and versions are preserved.')).toBeVisible();
    await page.getByRole('button', { name: 'Duplicate', exact: true }).click();
    await page.getByLabel('Destination event', { exact: true }).selectOption({ label: 'Unassigned event' });
    await page.getByRole('button', { name: 'Create duplicate' }).click();
    await expect(page.getByRole('dialog', { name: 'Duplicate form' })).not.toBeVisible();
    await expect(page.getByRole('textbox', { name: 'Form title', exact: true })).toHaveValue('Conference delegate application (copy) (copy)');
    await expect(page.getByLabel('Opens (Asia/Dhaka)')).toHaveValue('');
    await expect(page.getByLabel('Closes (Asia/Dhaka)')).toHaveValue('');
});
